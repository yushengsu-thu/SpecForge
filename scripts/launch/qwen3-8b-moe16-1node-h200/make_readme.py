#!/usr/bin/env python3
"""Write the model card of the Qwen3-8B 16 x 768 MoE drafter repo: training setting + train/acc per epoch (from launch.log)."""
import argparse, ast, re
from pathlib import Path

STEP_RE = re.compile(r"^step (\d+): (\{.*\})\s*$")

def metrics(log_path):
    out = {}
    for line in Path(log_path).read_text(errors="replace").splitlines():
        m = STEP_RE.match(line)
        if not m:
            continue
        try:
            d = ast.literal_eval(m.group(2))
        except Exception:
            continue
        out[int(m.group(1))] = {k.split("/")[-1]: v for k, v in d.items() if isinstance(v, (int, float))}
    return out

def at_epoch_end(ms, end, window=100):
    steps = sorted(s for s in ms if end - window < s <= end)
    if not steps:
        return None
    acc = [ms[s]["acc"] for s in steps if ms[s].get("acc") is not None]
    ce = [ms[s]["ce_loss"] for s in steps if ms[s].get("ce_loss") is not None]
    return {"acc": sum(acc) / len(acc) if acc else None, "ce": sum(ce) / len(ce) if ce else None}

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-dir", required=True)
    ap.add_argument("--steps-per-epoch", type=int, default=10764)
    ap.add_argument("--epochs-done", type=int, required=True)
    ap.add_argument("--epochs", type=int, default=6)
    ap.add_argument("--hf-repo", default="yushengsu/qwen3-8b-moe16x768-16A1-dspark")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    ms = metrics(Path(a.run_dir) / "launch.log")
    results = {}
    for k in range(1, a.epochs_done + 1):
        m = at_epoch_end(ms, k * a.steps_per_epoch)
        if m and m["acc"] is not None:
            results[k] = m
    best = max(results, key=lambda k: results[k]["acc"]) if results else None
    rows = []
    for k in range(1, a.epochs + 1):
        if k in results:
            star = " **(best)**" if k == best else ""
            rows.append(f"| {k} | `{k}ep/` | {k * a.steps_per_epoch} | {results[k]['acc']:.3f}{star} | {results[k]['ce']:.2f} |")
        elif k <= a.epochs_done:
            rows.append(f"| {k} | `{k}ep/` | {k * a.steps_per_epoch} | n/a | n/a |")
        else:
            rows.append(f"| {k} | `{k}ep/` | {k * a.steps_per_epoch} | (training) | |")
    best_line = f"Highest train/acc so far: **{results[best]['acc']:.3f}** at epoch {best} (`{best}ep/`)." if best else "No epoch finished yet."
    body = f"""---
license: other
base_model: Qwen/Qwen3-8B
tags: [speculative-decoding, dspark, draft-model, moe, sglang]
---

# Qwen3-8B DSpark MoE drafter (16 experts x 768, top-1)

One folder per finished epoch (`1ep/` … `{a.epochs}ep/`), each a complete SGLang-servable draft model
(`Qwen3MoeDSparkModel`, block_size 16, tokenizer included).

## Training setting

| | |
|---|---|
| Target model | `Qwen/Qwen3-8B` (BF16 capture / teacher, as in jiapingW/Qwen3-8b-dspark-SpecForge) |
| Draft model | jiapingW/Qwen3-8b-dspark-SpecForge's dense draft architecture with the FFN replaced by a Qwen3.5-MoE FFN: 5 full-attention layers, hidden 4096, **16 routed experts x 768 (= 12288 / 16), one per token, no shared expert**, 32 query / 8 KV heads of dim 128, target layers 1/9/17/25/33, Markov rank 256, no confidence head, causal, block 16; 1.13B params, 0.42B active per token. Router balanced with a selection bias (moved once per optimizer step) plus a 0.005 batch-wise aux loss. |
| Data | PerfectBlend regenerated by Qwen3-8B at temperature 0, non-thinking (`yaro1214/open_data`, 1,420,903 conversations, max_length 8192, qwen3-instruct template, no system prompt) |
| Recipe | jiapingW's protocol: global batch 132 (6 ranks x 2 x 11; 10,764 steps / epoch), AdamW lr 6e-4 cosine with a 4% warm-up, grad clip 1.0, DSpark CE 0.1 / L1 0.9, no confidence head, 512 anchors, decay gamma 7, NO_SHARD DDP, training block 16, seed 42 |
| Schedule | {a.epochs} epochs in one continuous run ({a.epochs * a.steps_per_epoch} steps), from scratch |
| Hardware | one 8x H200 node: 2 BF16 capture servers + 6 DDP ranks, features over Mooncake |

## train/acc per epoch

train/acc = mean draft-token accuracy over the block positions, averaged over the last 100 steps of the epoch.

| epoch | folder | step | train/acc | ce loss |
|---|---|---|---|---|
{chr(10).join(rows)}

{best_line}

## Links

- Code / recipe: https://github.com/sgl-project/SpecForge/pull/1022 (config; recipe and scripts on branch `dspark-v2-moe-launch`); dense reference: https://huggingface.co/jiapingW/Qwen3-8b-dspark-SpecForge
- Serve (the MoE draft class comes from SpecForge's serving package until SGLang ships it):
  `SGLANG_EXTERNAL_MODEL_PACKAGE=specforge.serving.sglang_models python -m sglang.launch_server --model-path Qwen/Qwen3-8B --speculative-algorithm DSPARK --speculative-draft-model-path <local copy of Nep/> --speculative-dspark-block-size 16 --speculative-draft-model-quantization unquant --attention-backend triton --speculative-draft-attention-backend triton`
"""
    Path(a.out).write_text(body)
    print(f"wrote {a.out} ({a.epochs_done} epoch(s) done; best epoch {best})")

if __name__ == "__main__":
    main()

"""dense-same bookkeeping: per-epoch metrics from launch.log -> epoch_results.json -> exp_read.me / HF README.

  record     --results R --launch-log L --epoch K --step S --steps-per-epoch P [--hf-url U]
             [--local-epoch J --global-step-offset O]   (continuation segment: epoch K is the segment's
             epoch J, S is the segment's own step, O is added to S for the recorded/global step)
  readme     --results R --out exp_read.me        (rewrites the table between the EPOCH_TABLE markers)
  hf-readme  --results R --out README.md            (model card for yushengsu/dense-same)

acc end / ce end = mean of the last 100 logged steps up to the epoch's end step; acc peak = max logged
train/acc inside the epoch (segment steps (J-1)*P < s <= S, J = K for the first segment).
"""
import argparse, json, os, re, sys, time

TOTAL_EPOCHS = 24  # 12 epochs + continuation to 18 + 6 more epochs (19-24)

STEP_RE = re.compile(r"step (\d+): (\{.*?\})(?=step \d+: \{|$)")
HEAD = "| epoch | end step | train/acc (last 100 steps) | acc peak | train/ce_loss (last 100 steps) | HF checkpoint | uploaded (UTC) |\n|---|---|---|---|---|---|---|\n"
START, END = "<!-- EPOCH_TABLE_START -->", "<!-- EPOCH_TABLE_END -->"


def parse_log(path):
    rows = []
    with open(path, errors="replace") as fh:
        for line in fh:
            if not line.startswith("step "):
                continue
            for m in STEP_RE.finditer(line.rstrip("\n")):
                d = m.group(2)
                a = re.search(r"'train/acc': ([-0-9.e]+)", d)
                c = re.search(r"'train/ce_loss': ([-0-9.e]+)", d)
                if a:
                    rows.append((int(m.group(1)), float(a.group(1)), float(c.group(1)) if c else None))
    return rows


def load(path):
    if os.path.exists(path):
        with open(path) as fh:
            return json.load(fh)
    return []


def save(path, rows):
    tmp = path + ".tmp"
    with open(tmp, "w") as fh:
        json.dump(rows, fh, indent=1)
    os.replace(tmp, path)


def record(a):
    rows = parse_log(a.launch_log)
    local_epoch = a.local_epoch if a.local_epoch is not None else a.epoch
    lo, hi = (local_epoch - 1) * a.steps_per_epoch, a.step
    window = [r for r in rows if a.step - 100 <= r[0] <= a.step]
    inside = [r[1] for r in rows if lo < r[0] <= hi]
    entry = {
        "epoch": a.epoch, "step": a.step + a.global_step_offset,
        "acc": round(sum(r[1] for r in window) / len(window), 4) if window else None,
        "acc_peak": round(max(inside), 4) if inside else None,
        "ce": round(sum(r[2] for r in window if r[2] is not None) / max(1, len([r for r in window if r[2] is not None])), 3) if window else None,
        "hf_url": a.hf_url, "uploaded": time.strftime("%Y-%m-%d %H:%M", time.gmtime()),
    }
    results = [r for r in load(a.results) if r["epoch"] != a.epoch] + [entry]
    results.sort(key=lambda r: r["epoch"])
    save(a.results, results)
    print(f"epoch {a.epoch} recorded: acc {entry['acc']} peak {entry['acc_peak']} ce {entry['ce']}")


def table(results, total=TOTAL_EPOCHS):
    by = {r["epoch"]: r for r in results}
    out = HEAD
    for ep in range(1, total + 1):
        r = by.get(ep)
        if r:
            link = f"[{ep}ep]({r['hf_url']})" if r.get("hf_url") else "-"
            out += f"| {ep} | {r['step']} | {r['acc']} | {r['acc_peak']} | {r['ce']} | {link} | {r['uploaded']} |\n"
        else:
            out += f"| {ep} | - | - | - | - | - | - |\n"
    best = max((r for r in results if r.get("acc_peak") is not None), key=lambda r: r["acc_peak"], default=None)
    if best:
        out += f"\nHighest train/acc so far: **{best['acc_peak']}** (epoch {best['epoch']}, peak value).\n"
    return out


def readme(a):
    text = open(a.out).read()
    s, e = text.index(START) + len(START), text.index(END)
    new = text[:s] + "\n" + table(load(a.results)) + text[e:]
    if new != text:
        open(a.out, "w").write(new)
        print("exp_read.me table updated")
    else:
        print("exp_read.me unchanged")


def hf_readme(a):
    results = load(a.results)
    body = f"""---
license: apache-2.0
base_model: Qwen/Qwen3-8B
tags: [speculative-decoding, dspark, specforge, draft-model]
---
# dense-same: Qwen3-8B DSpark dense drafter, up to 24 epochs

Draft model for `Qwen/Qwen3-8B` trained with [SpecForge](https://github.com/yushengsu-thu/SpecForge/tree/dense-same)
(branch `dense-same`): DSpark dense drafter, block size 16, no confidence head, 5 layers, hidden 4096, FFN 12288,
hyperparameters of the published Qwen3-8B dense DSpark run (global batch 128, AdamW lr 6e-4 cosine, 4% warm-up,
0.1 CE + 0.9 L1), 12 epochs on Open Perfect Blend regenerated by Qwen3-8B at temperature 0 (1,420,909 rows),
then weights-only continuations logged on the same W&B curve (AdamW reset each time): epoch 13 from the epoch-12
checkpoint (1% warm-up to 2e-4, 6-epoch cosine, prompt seed 54; that segment crashed in epoch 14), epochs 14-18 from
the epoch-13 checkpoint (1% warm-up to 1.88e-4 = the planned cosine value there, cosine to 0 over 5 epochs, prompt
seed 55), and epochs 19-24 from the epoch-18 checkpoint (1% warm-up to 2e-4, cosine to 0 over 6 epochs, prompt seed 60).
Each folder `<k>ep/` is the servable export of the checkpoint at the end of epoch k. Full parameters and log:
[exp_read.me](https://github.com/yushengsu-thu/SpecForge/blob/dense-same/exp_read.me).

{table(results)}
"""
    open(a.out, "w").write(body)


p = argparse.ArgumentParser(); sub = p.add_subparsers(dest="cmd", required=True)
r = sub.add_parser("record"); r.add_argument("--results", required=True); r.add_argument("--launch-log", required=True)
r.add_argument("--epoch", type=int, required=True); r.add_argument("--step", type=int, required=True)
r.add_argument("--steps-per-epoch", type=int, required=True); r.add_argument("--hf-url", default=None)
r.add_argument("--local-epoch", type=int, default=None); r.add_argument("--global-step-offset", type=int, default=0)
m = sub.add_parser("readme"); m.add_argument("--results", required=True); m.add_argument("--out", required=True)
h = sub.add_parser("hf-readme"); h.add_argument("--results", required=True); h.add_argument("--out", required=True)
args = p.parse_args()
{"record": record, "readme": readme, "hf-readme": hf_readme}[args.cmd](args)
